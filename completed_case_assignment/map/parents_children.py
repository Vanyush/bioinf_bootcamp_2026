def find_best_parents(edges, min_age, min_age_diff=800, max_distance=30):
    candidates = []  # (parent, child, distance, age_diff, score)
    
    for hg_a, hg_b, dist in edges:
        age_a = min_age.get(hg_a)
        age_b = min_age.get(hg_b)
        if age_a is None or age_b is None:
            continue  # пропускаем, если нет возраста
        
        # Направление: родитель тот, кто древнее (больше лет)
        if age_a > age_b and (age_a - age_b) >= min_age_diff:
            parent, child = hg_a, hg_b
            age_diff = age_a - age_b
        elif age_b > age_a and (age_b - age_a) >= min_age_diff:
            parent, child = hg_b, hg_a
            age_diff = age_b - age_a
        else:
            continue  # разница太小, не определяем
        
        # Фильтр по генетической дистанции
        if dist > max_distance:
            continue
        
        # Оценка надёжности: чем больше age_diff и чем меньше dist, тем выше score
        score = (age_diff / 1000.0) / (dist + 1) + (age_diff / 100000.0)
        candidates.append((parent, child, dist, age_diff, score))
    
    # Разрешение конфликтов: у каждого ребёнка оставляем только лучшего родителя
    best_for_child = {}
    for parent, child, dist, age_diff, score in candidates:
        if child not in best_for_child or score > best_for_child[child][4]:
            best_for_child[child] = (parent, child, dist, age_diff, score)
    
    # Преобразуем в список и сортируем по убыванию score
    unique_candidates = list(best_for_child.values())
    unique_candidates.sort(key=lambda x: x[4], reverse=True)
    
    return unique_candidates

