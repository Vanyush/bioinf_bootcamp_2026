def run_diagnostics(min_age, edges, min_age_diff, max_distance):
    print("\n=== ДИАГНОСТИКА ===\n")
    print(f"Найдено гаплогрупп с возрастами: {len(min_age)}")
    print(f"Найдено рёбер: {len(edges)}")
    
    print("\nПервые 10 гаплогрупп и их МАКСИМАЛЬНЫЙ возраст (самый древний образец):")
    sorted_ages = sorted(min_age.items(), key=lambda x: x[1], reverse=True)
    for i, (hg, age) in enumerate(sorted_ages[:10]):
        print(f"  {hg}: {age:.0f} лет")
    
    print("\nПервые 10 рёбер:")
    for i, (a, b, d) in enumerate(edges[:10]):
        print(f"  {a} -- {b} (дист.{d})")
    
    # Проверяем, сколько рёбер проходит по возрасту
    age_pass = 0
    age_diff_list = []
    for hg_a, hg_b, dist in edges:
        age_a = min_age.get(hg_a)
        age_b = min_age.get(hg_b)
        if age_a is not None and age_b is not None:
            diff = abs(age_a - age_b)
            age_diff_list.append(diff)
            if diff >= min_age_diff:
                age_pass += 1
    print(f"\nРёбер с разницей возраста ≥ {min_age_diff} лет: {age_pass} из {len(edges)}")
    if age_diff_list:
        print(f"  Минимальная разница: {min(age_diff_list):.0f} лет")
        print(f"  Максимальная разница: {max(age_diff_list):.0f} лет")
        print(f"  Средняя разница: {sum(age_diff_list)/len(age_diff_list):.0f} лет")
    
    # Проверяем, сколько рёбер проходит по дистанции
    dist_pass = sum(1 for _, _, d in edges if d <= max_distance)
    print(f"Рёбер с дистанцией ≤ {max_distance}: {dist_pass} из {len(edges)}")
    
    dist_list = [d for _, _, d in edges]
    if dist_list:
        print(f"  Минимальная дистанция: {min(dist_list)}")
        print(f"  Максимальная дистанция: {max(dist_list)}")
        print(f"  Медианная дистанция: {sorted(dist_list)[len(dist_list)//2]}")

