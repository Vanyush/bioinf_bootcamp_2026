# ============================================================
# Парсинг образцов (исправлен: используется 4-й столбец date_found)
# ============================================================

def parse_samples(text):
    lines = text.strip().splitlines()
    if not lines:
        return {}
    max_age = defaultdict(float)  # используем максимальный возраст (самый древний образец)
    for line in lines[1:]:
        if not line.strip():
            continue
        parts = line.split('\t')
        if len(parts) < 6:  # у нас 6 колонок
            continue
        hg = parts[1].strip()
        try:
            # date_found находится в 4-й колонке (индекс 3)
            age = float(parts[3].strip())
        except (ValueError, IndexError):
            continue
        # берём максимальный возраст (самый древний образец в гаплогруппе)
        if hg not in max_age or age > max_age[hg]:
            max_age[hg] = age
    return max_age

# ============================================================
# Парсинг рёбер
# ============================================================

def parse_edges(text):
    edges = []
    for line in text.strip().splitlines():
        match = re.search(r'HG(\d+).*?HG(\d+)', line)
        if not match:
            continue
        hg1 = f"HG{match.group(1)}"
        hg2 = f"HG{match.group(2)}"
        dist_match = re.search(r'дистанция:\s*(\d+)', line)
        dist = int(dist_match.group(1)) if dist_match else 9999
        edges.append((hg1, hg2, dist))
    return edges

