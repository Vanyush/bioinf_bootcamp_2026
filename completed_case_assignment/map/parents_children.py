def print_results(candidates, min_score=0.0, min_age_diff=800, max_distance=30):
    if not candidates:
        print("Не найдено достоверных родительско-дочерних связей.")
        print("Попробуйте уменьшить MIN_AGE_DIFF или увеличить MAX_DISTANCE.")
        return
    
    print("\n=== НАИБОЛЕЕ ВЕРОЯТНЫЕ РОДИТЕЛЬСКО-ДОЧЕРНИЕ СВЯЗИ ===\n")
    print(f"{'Родитель':<8} -> {'Ребёнок':<8} | {'Дист.':<6} | {'Разница лет':<12} | {'Score':<8}")
    print("-" * 60)
    for parent, child, dist, age_diff, score in candidates:
        if score < min_score:
            continue
        print(f"{parent:<8} -> {child:<8} | {dist:<6} | {age_diff:<12.0f} | {score:<8.4f}")
    
    print(f"\nПримечания:")
    print(f"  - Отфильтровано по разнице возрастов ≥ {min_age_diff} лет")
    print(f"  - Отфильтровано по генетической дистанции ≤ {max_distance}")
    print(f"  - Всего направленных рёбер после фильтрации: {len(candidates)}")
    print("  - У каждого ребёнка оставлен только лучший родитель (с максимальным Score)")

